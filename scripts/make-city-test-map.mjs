// Builds public/maps/citytest/ WITHOUT the editor: copies the height / splat / water / map.json of public/maps/junctions/ and writes a new
// roads.json + markers.json that exercise every city / highway / signals / crosswalk feature:  node scripts/make-city-test-map.mjs
// (the source map is never modified; re-running overwrites citytest). World = 1000 m, y = terrain height sampled from the source heightmap.
//
//   city grid (all `type: city`, width 10 m, signStyle us):
//     H1  z=150  x 60..430     (lamps on its left edge: shifted outside the footpath)
//     H2  z=293  x 60..360 city, then COUNTRY from x=360 to 620 (type change = footpath end ramp); crosswalk at (230,293) city and (520,293) country
//     V1  x=150  z 60..430     crosswalk at (150,100); crosses H1 + H2 (4-way signals), meets O1 at (150,220)
//     V2  x=300  z 60..293     crosses H1 at (300,150) (4-way, FORCED ROUNDABOUT by a marker), meets O1 (300,220) and H2 (300,293) as T junctions
//     O1  z=220  x 150..300    one-way (150 -> 300) city street, 6 m wide
//   marker 'junction_plain' at (152,222) forces a plain patch at the O1 / V1 T junction (the other three signals junctions stay signals)
//   self-crossing road (id 8, country figure-eight centred (800,160)): a road meeting itself, 4-arm roundabout at the crossing
//   highway HW  z=470 x 480..950  width 20 (2 lanes per direction + median barrier), guardrails; country road CR (x=700, z 700..478) joins it -> plain junction
import fs from 'node:fs';
import path from 'node:path';

const src = path.resolve('public/maps/junctions'), dst = path.resolve('public/maps/citytest');
fs.mkdirSync(dst, { recursive: true });
for (const f of fs.readdirSync(src)) if (!['roads.json', 'markers.json', 'map.json'].includes(f)) fs.copyFileSync(path.join(src, f), path.join(dst, f));
const mj = JSON.parse(fs.readFileSync(path.join(src, 'map.json'), 'utf8'));
mj.files.markers = 'markers.json';
fs.writeFileSync(path.join(dst, 'map.json'), JSON.stringify(mj, null, 1));

const N = mj.N, W = mj.worldSizeMeters, cell = W / N, buf = fs.readFileSync(path.join(src, 'heightmap.r16'));
const H = new Uint16Array(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length));
const heightAt = (x, z) => { // same bilinear rule as the loader's heightAt (no junction stamping)
  const cl = (v) => Math.min(Math.max(v, 0), N - 1);
  const fx = cl(x / cell - 0.5), fz = cl(z / cell - 0.5), i = Math.min(Math.floor(fx), N - 2), j = Math.min(Math.floor(fz), N - 2), tx = fx - i, tz = fz - j;
  const h = (a, b) => H[b * N + a] / 65535 * mj.maxHeightMeters;
  const a = h(i, j) + (h(i + 1, j) - h(i, j)) * tx, b = h(i, j + 1) + (h(i + 1, j + 1) - h(i, j + 1)) * tx;
  return a + (b - a) * tz;
};
// pts: [x, z, extra?] with extra = per-point metadata overrides (e.g. { features: ['crosswalk'] }); meta = default metadata for every point
const road = (id, width, pts, meta = {}) => ({
  id, widthMeters: width,
  points: pts.map(([x, z, extra = {}]) => ({ nx: x / W, nz: z / W, x, y: heightAt(x, z), z, bridge: false, ...meta, ...extra })),
});
const city = { type: 'city' };
const roads = [
  road(1, 10, [[60, 150], [150, 150], [230, 150], [300, 150], [380, 150], [430, 150]], { ...city, edgeL: 'lamps' }),
  road(2, 10, [[60, 293, city], [150, 293, city], [230, 293, { ...city, features: ['crosswalk'] }], [300, 293, city], [360, 293], [440, 293], [520, 293, { features: ['crosswalk'] }], [620, 293]]),
  road(3, 10, [[150, 60], [150, 100, { features: ['crosswalk'] }], [150, 150], [150, 220], [150, 293], [150, 360], [150, 430]], city),
  road(4, 10, [[300, 60], [300, 150], [300, 220], [300, 293]], city),
  road(5, 6, [[150, 220], [225, 220], [300, 220]], { ...city, oneway: true }),
  road(6, 20, [[480, 470], [580, 470], [700, 470], [820, 470], [940, 470]], { type: 'highway', edgeL: 'guardrail', edgeR: 'guardrail' }),
  road(7, 8, [[700, 700], [700, 600], [700, 520], [700, 478]]),
  // a road that crosses ITSELF (figure-eight, country): the crossing at (800,160) becomes a 4-arm junction of one road
  road(8, 8, Array.from({ length: 34 }, (_, i) => { const t = -0.6 + i * (Math.PI + 1.2) / 33; return [Math.round((800 + 120 * Math.sin(t)) * 10) / 10, Math.round((160 + 80 * Math.sin(t) * Math.cos(t)) * 10) / 10]; })),
];
fs.writeFileSync(path.join(dst, 'roads.json'), JSON.stringify({
  formatVersion: 1,
  note: 'City test map generated by scripts/make-city-test-map.mjs (nx,nz normalized, x,z metres, y terrain height). See that script for the layout.',
  roads,
}, null, 1));

const marker = (id, name, tags, color, x, z, yaw = 0) => ({ id, name, tags, color, x, z, y: heightAt(x, z), nx: x / W, nz: z / W, yaw, radius: 0, props: {}, yOffset: 0 });
fs.writeFileSync(path.join(dst, 'markers.json'), JSON.stringify({
  version: 1,
  note: 'roundabout marker forces a roundabout at the V2/H1 crossing; junction_plain forces a plain patch at the V1/O1 T junction (junction styles: see mapLoader.js).',
  markers: [
    marker(1, 'city_roundabout', ['roundabout'], '#30a0ff', 302, 152),
    marker(2, 'plain_junction', ['junction_plain'], '#ffd400', 152, 222),
    marker(3, 'player_start', ['spawn'], '#ff3b30', 80, 147, 0),
  ],
}, null, 1));
console.log('wrote', dst, '-', roads.length, 'roads');
